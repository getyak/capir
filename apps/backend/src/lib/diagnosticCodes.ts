/**
 * Extract every recognized diagnostic code carried by an untrusted exception,
 * in precedence order (`code` property first, then `message`), deduplicated.
 * Both fields are finite-allowlist gated exactly like
 * {@link recognizedDiagnosticCode}: retry classification may consider all
 * recognized fields while detail display keeps the first-code priority.
 */
export function recognizedDiagnosticCodes(
  error: unknown,
  recognized: ReadonlySet<string>,
): string[] {
  const codes: string[] = [];
  const propertyCode =
    error && typeof error === "object"
      ? (error as { code?: unknown }).code
      : undefined;
  if (typeof propertyCode === "string" && recognized.has(propertyCode)) {
    codes.push(propertyCode);
  }
  const messageCode = error instanceof Error ? error.message : undefined;
  if (
    typeof messageCode === "string" &&
    recognized.has(messageCode) &&
    !codes.includes(messageCode)
  ) {
    codes.push(messageCode);
  }
  return codes;
}

/**
 * Extract the first recognized diagnostic code from an untrusted exception.
 * Neither an arbitrary `code` property, a code-shaped `message`, nor a
 * constructor/name string is trusted unless the exact code is in the finite
 * allowlist; otherwise `undefined` so optional detail can be omitted.
 */
export function recognizedDiagnosticCode(
  error: unknown,
  recognized: ReadonlySet<string>,
): string | undefined {
  return recognizedDiagnosticCodes(error, recognized)[0];
}

/** Fixed-fallback mapping for boundaries that must always report a code. */
export function boundedDiagnosticCode(
  error: unknown,
  recognized: ReadonlySet<string>,
  fallback: string,
): string {
  return recognizedDiagnosticCode(error, recognized) ?? fallback;
}
