import { describe, expect, it } from "vitest";

import {
  boundedDiagnosticCode,
  BROWSER_ERROR_CODES,
  CONTACT_RESEARCH_CLIENT_ERROR_CODES,
  CONTACT_RESEARCH_ERROR_CODES,
  CONTACT_RESEARCH_SERVER_ERROR_CODES,
  CONTACT_RESEARCH_SERVER_ERROR_CODE_SET,
  recognizedDiagnosticCode,
  recognizedDiagnosticCodes,
  RESEARCH_TOOL_ERROR_CODE_SET,
  SOCKET_TRANSIENT_ERROR_CODES,
} from "./diagnosticCodes.js";

describe("diagnostic code allowlists", () => {
  it("preserves every genuinely supported producer and transport code", () => {
    for (const code of [
      // Real socket transient conditions keep retry semantics.
      "ECONNRESET",
      "ECONNREFUSED",
      "ETIMEDOUT",
      "EPIPE",
      "EAI_AGAIN",
      // Explicit browser resource budget limits.
      "BROWSER_HTTP_LIMIT",
      "BROWSER_RESPONSE_BYTE_LIMIT",
      // Current auth/query/response limits.
      "BROWSER_EXECUTOR_UNAUTHORIZED",
      "BROWSER_REQUEST_TOO_LARGE",
      "BROWSER_RESPONSE_TOO_LARGE",
      "CONTACT_RESEARCH_QUERY_OUT_OF_SCOPE",
      "CONTACT_RESEARCH_PRIVATE_LOOKUP_PROHIBITED",
      "CONTACT_RESEARCH_RESPONSE_TOO_LARGE",
      "CONTACT_RESEARCH_TIMEOUT",
      "CONTACT_RESEARCH_READBACK_MISMATCH",
      // Supported fault-injection codes used by existing tests.
      "CONTACT_RESEARCH_INJECTED_TRANSIENT",
      "CONTACT_RESEARCH_UNAVAILABLE",
      "CONTACT_RESEARCH_CHANNEL_TRANSIENT",
      "CONTACT_RESEARCH_CHANNEL_FAILED",
    ]) {
      expect(RESEARCH_TOOL_ERROR_CODE_SET.has(code)).toBe(true);
      expect(recognizedDiagnosticCode(new Error(code), RESEARCH_TOOL_ERROR_CODE_SET)).toBe(code);
    }
  });

  it("keeps every transient code recognized for retry classification", () => {
    for (const code of SOCKET_TRANSIENT_ERROR_CODES) {
      expect(RESEARCH_TOOL_ERROR_CODE_SET.has(code)).toBe(true);
    }
    for (const code of ["CONTACT_RESEARCH_HTTP_429", "CONTACT_RESEARCH_HTTP_500",
      "CONTACT_RESEARCH_HTTP_502", "CONTACT_RESEARCH_HTTP_503", "CONTACT_RESEARCH_HTTP_504"]) {
      expect(RESEARCH_TOOL_ERROR_CODE_SET.has(code)).toBe(true);
    }
  });

  it("maps recognized codes from either the code property or the message", () => {
    // Real socket failures carry the code property; policy faults are thrown
    // as fixed messages. Both channels only honor exact allowlist membership.
    expect(recognizedDiagnosticCode(
      Object.assign(new Error("socket hang up"), { code: "ECONNRESET" }),
      RESEARCH_TOOL_ERROR_CODE_SET,
    )).toBe("ECONNRESET");
    expect(recognizedDiagnosticCode(
      new Error("CONTACT_RESEARCH_TIMEOUT"),
      RESEARCH_TOOL_ERROR_CODE_SET,
    )).toBe("CONTACT_RESEARCH_TIMEOUT");
  });

  it("refuses arbitrary error.code, code-shaped messages, and name strings", () => {
    for (const error of [
      Object.assign(new Error("boom"), { code: "SECRET_CODE_CANARY" }),
      Object.assign(new Error("CONTACT_RESEARCH_ARBITRARY_SECRET_CANARY"), { code: "BROWSER_ARBITRARY_SECRET" }),
      new Error("SECRET_MESSAGE_CANARY"),
      new Error("CONTACT_RESEARCH_ARBITRARY_SECRET_CANARY"),
      new Error("BROWSER_ARBITRARY_SECRET_CANARY"),
      Object.assign(new Error("SECRET_MESSAGE_CANARY"), {
        name: "BROWSER_SECRET_NAME_CANARY",
        cause: new Error("SECRET_CAUSE_CANARY"),
      }),
    ]) {
      expect(recognizedDiagnosticCode(error, RESEARCH_TOOL_ERROR_CODE_SET)).toBe(undefined);
    }
    expect(recognizedDiagnosticCode("SECRET_STRING", RESEARCH_TOOL_ERROR_CODE_SET)).toBe(undefined);
    expect(recognizedDiagnosticCode(null, RESEARCH_TOOL_ERROR_CODE_SET)).toBe(undefined);
    const fallback = boundedDiagnosticCode(
      new Error("BROWSER_ARBITRARY_SECRET_CANARY"),
      RESEARCH_TOOL_ERROR_CODE_SET,
      "CONTACT_RESEARCH_UNAVAILABLE",
    );
    expect(fallback).toBe("CONTACT_RESEARCH_UNAVAILABLE");
    expect(fallback).not.toContain("CANARY");
  });

  it("prefers the recognized code property over a foreign message", () => {
    const error = Object.assign(new Error("CONTACT_RESEARCH_ARBITRARY_XYZ"), {
      code: "ECONNRESET",
    });
    expect(recognizedDiagnosticCode(error, RESEARCH_TOOL_ERROR_CODE_SET)).toBe("ECONNRESET");
  });

  it("keeps host and client inventories finite and free of shape regexes", () => {
    for (const code of [...CONTACT_RESEARCH_ERROR_CODES, ...BROWSER_ERROR_CODES]) {
      expect(code).toMatch(/^[A-Z][A-Z0-9_]+$/u);
    }
    expect(new Set(CONTACT_RESEARCH_ERROR_CODES).size).toBe(CONTACT_RESEARCH_ERROR_CODES.length);
    expect(new Set(BROWSER_ERROR_CODES).size).toBe(BROWSER_ERROR_CODES.length);
  });

  it("never accepts client-owned diagnostics from a server error body", () => {
    // Status-derived codes are owned and generated by the client from the real
    // status line, and timeout/readback/socket/test-injection codes are local
    // constructors: none of them may be claimed by a server payload.
    for (const clientOwned of [
      ...CONTACT_RESEARCH_CLIENT_ERROR_CODES,
    ]) {
      expect(CONTACT_RESEARCH_SERVER_ERROR_CODE_SET.has(clientOwned)).toBe(false);
    }
    // The server vocabulary is exactly the real host producers plus browse and
    // socket forwarding.
    for (const serverCode of [
      ...CONTACT_RESEARCH_SERVER_ERROR_CODES,
      "BROWSER_HTTP_LIMIT",
      "BROWSER_RESPONSE_BYTE_LIMIT",
      "ECONNRESET",
    ]) {
      expect(CONTACT_RESEARCH_SERVER_ERROR_CODE_SET.has(serverCode)).toBe(true);
    }
    expect(CONTACT_RESEARCH_SERVER_ERROR_CODE_SET.has("BROWSER_ARBITRARY_SECRET")).toBe(false);
  });

  it("keeps the combined set classifying both sides with first-code priority", () => {
    const dual = Object.assign(new Error("CONTACT_RESEARCH_TIMEOUT"), {
      code: "CONTACT_RESEARCH_UNAVAILABLE",
    });
    expect(recognizedDiagnosticCodes(dual, RESEARCH_TOOL_ERROR_CODE_SET)).toEqual([
      "CONTACT_RESEARCH_UNAVAILABLE",
      "CONTACT_RESEARCH_TIMEOUT",
    ]);
    expect(recognizedDiagnosticCode(dual, RESEARCH_TOOL_ERROR_CODE_SET)).toBe(
      "CONTACT_RESEARCH_UNAVAILABLE",
    );
  });
});
