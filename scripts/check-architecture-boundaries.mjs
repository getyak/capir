export function extractTypeScriptContractVersion(source) {
  const match = source.match(
    /^export const CONTRACT_VERSION = "(\d{4}-\d{2}-\d{2}\.\d+)" as const;\r?\n?/u,
  );
  const declarations = [
    ...source.matchAll(/^export const CONTRACT_VERSION\s*=/gmu),
  ];
  return match && declarations.length === 1 ? match[1] : null;
}

export function renderSwiftContractMirror(version) {
  return [
    "// Generated by `pnpm architecture:contract:sync` from packages/contracts/src/constants.ts.",
    "enum TalentSignalAPIContract {",
    `    static let version = "${version}"`,
    "}",
  ].join("\n");
}

function swiftCodeMask(source) {
  const mask = source.split("");
  let index = 0;
  let state = "code";
  let blockDepth = 0;

  const hide = (at) => {
    if (mask[at] !== "\n" && mask[at] !== "\r") mask[at] = " ";
  };

  while (index < source.length) {
    if (state === "code") {
      if (source.startsWith("//", index)) {
        hide(index);
        hide(index + 1);
        index += 2;
        state = "line-comment";
      } else if (source.startsWith("/*", index)) {
        hide(index);
        hide(index + 1);
        index += 2;
        blockDepth = 1;
        state = "block-comment";
      } else if (source.startsWith('\"\"\"', index)) {
        hide(index);
        hide(index + 1);
        hide(index + 2);
        index += 3;
        state = "multiline-string";
      } else if (source[index] === '"') {
        hide(index);
        index += 1;
        state = "string";
      } else {
        index += 1;
      }
      continue;
    }

    if (state === "line-comment") {
      if (source[index] === "\n" || source[index] === "\r") {
        state = "code";
      } else {
        hide(index);
      }
      index += 1;
      continue;
    }

    if (state === "block-comment") {
      if (source.startsWith("/*", index)) {
        hide(index);
        hide(index + 1);
        index += 2;
        blockDepth += 1;
      } else if (source.startsWith("*/", index)) {
        hide(index);
        hide(index + 1);
        index += 2;
        blockDepth -= 1;
        if (blockDepth === 0) state = "code";
      } else {
        hide(index);
        index += 1;
      }
      continue;
    }

    if (state === "multiline-string") {
      if (source.startsWith('\"\"\"', index)) {
        hide(index);
        hide(index + 1);
        hide(index + 2);
        index += 3;
        state = "code";
      } else {
        hide(index);
        index += 1;
      }
      continue;
    }

    hide(index);
    if (source[index] === "\\") {
      if (index + 1 < source.length) hide(index + 1);
      index += 2;
    } else if (source[index] === '"') {
      index += 1;
      state = "code";
    } else {
      index += 1;
    }
  }

  return mask.join("");
}

function findSingleSwiftContractBlock(source) {
  const anchored = source.match(swiftContractAnchorPattern);
  const managedBlock = anchored?.groups?.managed;
  if (!anchored || !managedBlock) return null;
  const blockStart = anchored[0].length - managedBlock.length;
  const declarationIndex = blockStart + managedBlock.indexOf("enum ");
  const declarations = [
    ...swiftCodeMask(source).matchAll(swiftContractDeclarationPattern),
  ];
  if (
    declarations.length !== 1 ||
    declarations[0].index !== declarationIndex
  ) {
    return null;
  }
  return { index: blockStart, text: managedBlock };
}

function normalizedLineEndings(source) {
  return source.replace(/\r\n/gu, "\n");
}

export function parseMigrationManifest(source) {
  try {
    const manifest = JSON.parse(source);
    if (
      manifest?.schemaVersion !== "talent-signal-migrations.v1" ||
      !Array.isArray(manifest.migrations) ||
      !manifest.migrations.every((entry) => typeof entry === "string")
    ) {
      return null;
    }
    return manifest.migrations;
  } catch {
    return null;
  }
}

export function validateMigrationInventory(migrationNames, sqlFiles) {
  const errors = [];
  if (!migrationNames) return ["Cannot parse the migration manifest."];

  const uniqueNames = new Set(migrationNames);
  if (uniqueNames.size !== migrationNames.length) {
    errors.push("Migration manifest contains a duplicate full migration name.");
  }

  for (const name of migrationNames) {
    if (!/^\d{3}_[a-z0-9_]+$/u.test(name)) {
      errors.push(`Migration name is not canonical: ${name}`);
    }
  }

  const listedFiles = new Set(migrationNames.map((name) => `${name}.sql`));
  const actualFiles = new Set(sqlFiles);
  for (const filename of [...actualFiles].sort()) {
    if (!listedFiles.has(filename)) {
      errors.push(`Migration SQL is not listed in the manifest: ${filename}`);
    }
  }
  for (const filename of [...listedFiles].sort()) {
    if (!actualFiles.has(filename)) {
      errors.push(`Migration manifest entry has no SQL file: ${filename}`);
    }
  }

  const namesByPrefix = new Map();
  for (const name of migrationNames) {
    const prefix = name.slice(0, 3);
    const names = namesByPrefix.get(prefix) ?? [];
    names.push(name);
    namesByPrefix.set(prefix, names);
  }
  for (const [prefix, names] of namesByPrefix) {
    if (names.length < 2) continue;
    const allowed = LEGACY_MIGRATION_PREFIX_COLLISIONS.get(prefix);
    if (
      !allowed ||
      JSON.stringify([...names].sort()) !== JSON.stringify([...allowed].sort())
    ) {
      errors.push(
        `Migration prefix ${prefix} is duplicated outside the frozen legacy baseline: ${names.join(", ")}`,
      );
    }
  }

  return errors;
}

export function migrationHistoryDigest(migrationNames, readSql) {
  const entries = migrationNames.map((name) => [
    name,
    createHash("sha256").update(readSql(name)).digest("hex"),
  ]);
  return createHash("sha256").update(JSON.stringify(entries)).digest("hex");
}

export function discoverWorkspaceManifests(root) {
  const manifests = ["package.json"];
  for (const parent of ["apps", "packages"]) {
    for (const entry of readdirSync(resolve(root, parent), {
      withFileTypes: true,
    })) {
      if (!entry.isDirectory()) continue;
      const manifestPath = `${parent}/${entry.name}/package.json`;
      if (existsSync(resolve(root, manifestPath))) manifests.push(manifestPath);
    }
  }
  return manifests.sort();
}

export function parseWorkspacePatterns(source) {
  const packagesBlock = source.match(
    /^packages:\r?\n((?:[ \t]+-[^\r\n]+\r?\n?)+)/mu,
  )?.[1];
  if (!packagesBlock) return null;
  return [...packagesBlock.matchAll(/^[ \t]+-[ \t]+["']?([^"'\s]+)["']?\s*$/gmu)].map(
    (match) => match[1],
  );
}

function internalDependencyTarget(name, specification, options) {
  if (options?.internalPackageNames?.has(name)) return name;
  if (name.startsWith("@talent-signal/")) return name;
  if (typeof specification !== "string") return null;

  const workspaceValue = specification.startsWith("workspace:")
    ? specification.slice("workspace:".length)
    : null;
  if (workspaceValue && options?.internalPackageNames) {
    const aliasTarget = [...options.internalPackageNames]
      .sort((left, right) => right.length - left.length)
      .find(
        (packageName) =>
          workspaceValue === packageName ||
          workspaceValue.startsWith(`${packageName}@`),
    );
    if (aliasTarget) return aliasTarget;
  }
  const canonicalAlias = workspaceValue?.match(
    /^(@talent-signal\/[^@]+)(?:@.+)?$/u,
  );
  if (canonicalAlias) return canonicalAlias[1];

  const localPath = workspaceValue?.startsWith(".")
    ? workspaceValue
    : specification.match(/^(?:file|link):(.+)$/u)?.[1];
  if (!localPath || !options?.root || !options.manifestPath) return null;
  const targetDirectory = resolve(
    options.root,
    dirname(options.manifestPath),
    localPath,
  );
  return options.packageNameByDirectory?.get(targetDirectory) ?? null;
}

export function unexpectedWorkspaceDependencies(
  manifest,
  allowedNames,
  options,
) {
  const dependencyEntries = [
    manifest.dependencies,
    manifest.devDependencies,
    manifest.optionalDependencies,
    manifest.peerDependencies,
  ].flatMap((dependencies) => Object.entries(dependencies ?? {}));
  const allowed = new Set(allowedNames);
  const targets = new Set(
    dependencyEntries
      .map(([name, specification]) =>
        internalDependencyTarget(name, specification, options),
      )
      .filter(Boolean),
  );
  return [...targets].filter((name) => !allowed.has(name)).sort();
}

function pathIsInside(directory, candidate) {
  const pathFromDirectory = relative(directory, candidate);
  return (
    pathFromDirectory === "" ||
    (pathFromDirectory !== ".." &&
      !pathFromDirectory.startsWith(`..${sep}`))
  );
}

function listWorkspaceSourceFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!ignoredSourceDirectories.has(entry.name)) {
        files.push(...listWorkspaceSourceFiles(resolve(directory, entry.name)));
      }
    } else if (entry.isFile() && sourceExtensions.has(extname(entry.name))) {
      files.push(resolve(directory, entry.name));
    }
  }
  return files;
}

function owningWorkspace(candidate, workspaceEntries) {
  return workspaceEntries.find(({ directory }) =>
    pathIsInside(directory, candidate),
  );
}

function packageTarget(specifier, workspaceEntries) {
  return workspaceEntries.find(
    ({ name }) => specifier === name || specifier.startsWith(`${name}/`),
  );
}

function tsconfigBoundaryErrors(root, workspace, workspaceEntries) {
  const tsconfigPath = resolve(workspace.directory, "tsconfig.json");
  if (!existsSync(tsconfigPath)) return [];

  const loadedConfig = ts.readConfigFile(tsconfigPath, ts.sys.readFile);
  if (loadedConfig.error) {
    return [`Cannot parse ${relative(root, tsconfigPath)}.`];
  }
  const parsedConfig = ts.parseJsonConfigFileContent(
    loadedConfig.config,
    ts.sys,
    workspace.directory,
    undefined,
    tsconfigPath,
  );
  const compilerOptions = parsedConfig.options;
  const baseDirectory =
    compilerOptions.pathsBasePath ??
    compilerOptions.baseUrl ??
    workspace.directory;
  const errors = [];
  for (const [alias, targets] of Object.entries(compilerOptions.paths ?? {})) {
    if (!Array.isArray(targets)) continue;
    for (const target of targets) {
      if (typeof target !== "string") continue;
      const targetWorkspace = owningWorkspace(
        resolve(baseDirectory, target),
        workspaceEntries,
      );
      if (targetWorkspace && targetWorkspace !== workspace) {
        errors.push(
          `${relative(root, tsconfigPath)} maps ${alias} across the ${workspace.name} -> ${targetWorkspace.name} workspace boundary; import the target package instead.`,
        );
      }
    }
  }
  return errors;
}

function staticModuleSpecifiers(sourcePath, source) {
  const sourceFile = ts.createSourceFile(
    sourcePath,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const specifiers = [];
  const recordLiteral = (node) => {
    if (node && ts.isStringLiteralLike(node)) specifiers.push(node.text);
  };
  const visit = (node) => {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) {
      recordLiteral(node.moduleSpecifier);
    } else if (
      ts.isImportEqualsDeclaration(node) &&
      ts.isExternalModuleReference(node.moduleReference)
    ) {
      recordLiteral(node.moduleReference.expression);
    } else if (
      ts.isCallExpression(node) &&
      (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
        (ts.isIdentifier(node.expression) && node.expression.text === "require"))
    ) {
      recordLiteral(node.arguments[0]);
    } else if (
      ts.isImportTypeNode(node) &&
      ts.isLiteralTypeNode(node.argument)
    ) {
      recordLiteral(node.argument.literal);
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  specifiers.push(
    ...sourceFile.referencedFiles.map(({ fileName }) => fileName),
    ...sourceFile.typeReferenceDirectives.map(({ fileName }) => fileName),
  );
  return specifiers;
}

export function workspaceSourceBoundaryErrors(root, workspaceEntries) {
  const errors = [];
  for (const workspace of workspaceEntries) {
    errors.push(...tsconfigBoundaryErrors(root, workspace, workspaceEntries));
    const allowed = new Set(workspace.allowedNames);
    for (const sourcePath of listWorkspaceSourceFiles(workspace.directory)) {
      const source = readFileSync(sourcePath, "utf8");
      for (const specifier of staticModuleSpecifiers(sourcePath, source)) {
        if (specifier.startsWith(".")) {
          const targetWorkspace = owningWorkspace(
            resolve(dirname(sourcePath), specifier),
            workspaceEntries,
          );
          if (targetWorkspace && targetWorkspace !== workspace) {
            errors.push(
              `${relative(root, sourcePath)} imports ${specifier} across the ${workspace.name} -> ${targetWorkspace.name} workspace boundary; import the target package instead.`,
            );
          }
          continue;
        }
        const targetWorkspace = packageTarget(specifier, workspaceEntries);
        if (targetWorkspace && !allowed.has(targetWorkspace.name)) {
          errors.push(
            `${relative(root, sourcePath)} imports forbidden workspace package ${targetWorkspace.name} from ${workspace.name}.`,
          );
        }
      }
    }
  }
  return [...new Set(errors)].sort();
}

export function countLines(content) {
  if (content.length === 0) return 0;
  const lineBreaks = content.match(/\r\n|[\n\r\u2028\u2029]/gu)?.length ?? 0;
  return /(?:\r\n|[\n\r\u2028\u2029])$/u.test(content)
    ? lineBreaks
    : lineBreaks + 1;
}

export function checkArchitectureBoundaries(root = process.cwd(), options = {}) {
  const errors = [];
  const contractSource = readFileSync(resolve(root, CONTRACT_SOURCE), "utf8");
  const contractVersion = extractTypeScriptContractVersion(contractSource);
  if (!contractVersion) {
    errors.push(
      `Expected one canonical CONTRACT_VERSION declaration at the start of ${CONTRACT_SOURCE}.`,
    );
  } else {
    const swiftSource = readFileSync(resolve(root, IOS_CONTRACT_MIRROR), "utf8");
    const expectedMirror = renderSwiftContractMirror(contractVersion);
    const managedBlock = findSingleSwiftContractBlock(swiftSource);
    if (
      !managedBlock ||
      normalizedLineEndings(managedBlock.text) !== expectedMirror
    ) {
      errors.push(
        `iOS contract mirror drifted from ${CONTRACT_SOURCE}; run pnpm architecture:contract:sync.`,
      );
    }
  }

  const migrationNames = parseMigrationManifest(
    readFileSync(resolve(root, MIGRATION_MANIFEST), "utf8"),
  );
  const migrationFiles = readdirSync(resolve(root, MIGRATION_DIRECTORY)).filter(
    (filename) => filename.endsWith(".sql"),
  );
  const migrationErrors = validateMigrationInventory(
    migrationNames,
    migrationFiles,
  );
  errors.push(...migrationErrors);

  const frozenMigrationCount =
    options.frozenMigrationCount ?? FROZEN_MIGRATION_COUNT;
  const frozenMigrationDigest =
    options.frozenMigrationDigest ?? FROZEN_MIGRATION_DIGEST;
  if (migrationNames && frozenMigrationCount > 0) {
    if (migrationNames.length < frozenMigrationCount) {
      errors.push(
        `Migration history was shortened below the frozen ${frozenMigrationCount}-entry baseline.`,
      );
    } else if (migrationNames.length > frozenMigrationCount) {
      errors.push(
        `Migration manifest has ${migrationNames.length - frozenMigrationCount} unfrozen entry or entries; append them, then advance the reviewed frozen count and digest.`,
      );
    } else {
      const frozenNames = migrationNames;
      const frozenFilesExist = frozenNames.every((name) =>
        existsSync(resolve(root, MIGRATION_DIRECTORY, `${name}.sql`)),
      );
      if (
        frozenFilesExist &&
        migrationHistoryDigest(frozenNames, (name) =>
          readFileSync(
            resolve(root, MIGRATION_DIRECTORY, `${name}.sql`),
            "utf8",
          ),
        ) !== frozenMigrationDigest
      ) {
        errors.push(
          "Applied migration history changed; preserve the frozen names, order, and SQL, then append a new migration.",
        );
      }
    }
  }

  const discoveredManifests = discoverWorkspaceManifests(root);
  const workspacePatterns = parseWorkspacePatterns(
    readFileSync(resolve(root, WORKSPACE_CONFIGURATION), "utf8"),
  );
  if (
    !workspacePatterns ||
    JSON.stringify(workspacePatterns) !== JSON.stringify(WORKSPACE_PATTERNS)
  ) {
    errors.push(
      `${WORKSPACE_CONFIGURATION} changed its package roots; declare the new discovery and dependency boundary before merging.`,
    );
  }
  const discoveredSet = new Set(discoveredManifests);
  for (const manifestPath of discoveredManifests) {
    if (!WORKSPACE_BOUNDARIES.has(manifestPath)) {
      errors.push(
        `Workspace manifest has no declared architecture boundary: ${manifestPath}.`,
      );
    }
  }
  for (const manifestPath of WORKSPACE_BOUNDARIES.keys()) {
    if (!discoveredSet.has(manifestPath)) {
      errors.push(`Configured workspace manifest is missing: ${manifestPath}.`);
    }
  }

  const packageNameByDirectory = new Map();
  const manifestPathByPackageName = new Map();
  const manifests = new Map();
  for (const manifestPath of discoveredManifests) {
    const manifest = JSON.parse(
      readFileSync(resolve(root, manifestPath), "utf8"),
    );
    manifests.set(manifestPath, manifest);
    const boundary = WORKSPACE_BOUNDARIES.get(manifestPath);
    if (boundary && manifest.name !== boundary.name) {
      errors.push(
        `Workspace package name changed at ${manifestPath}: expected ${boundary.name}, found ${manifest.name ?? "missing"}.`,
      );
    }
    if (manifest.name) {
      const duplicatePath = manifestPathByPackageName.get(manifest.name);
      if (duplicatePath) {
        errors.push(
          `Workspace package name is duplicated: ${manifest.name} appears in ${duplicatePath} and ${manifestPath}.`,
        );
      } else {
        manifestPathByPackageName.set(manifest.name, manifestPath);
      }
      packageNameByDirectory.set(
        resolve(root, dirname(manifestPath)),
        manifest.name,
      );
    }
  }
  const internalPackageNames = new Set(manifestPathByPackageName.keys());
  for (const [manifestPath, boundary] of WORKSPACE_BOUNDARIES) {
    const manifest = manifests.get(manifestPath);
    if (!manifest) continue;
    const unexpected = unexpectedWorkspaceDependencies(manifest, boundary.allowedNames, {
      internalPackageNames,
      manifestPath,
      packageNameByDirectory,
      root,
    });
    if (unexpected.length) {
      errors.push(
        `${manifest.name ?? manifestPath} adds forbidden inward dependencies: ${unexpected.join(", ")}`,
      );
    }
  }
  const workspaceEntries = [...WORKSPACE_BOUNDARIES.entries()]
    .filter(([manifestPath]) => manifestPath !== "package.json")
    .map(([manifestPath, boundary]) => ({
      allowedNames: boundary.allowedNames,
      directory: resolve(root, dirname(manifestPath)),
      manifestPath,
      name: boundary.name,
    }));
  errors.push(...workspaceSourceBoundaryErrors(root, workspaceEntries));

  for (const [relativePath, maximumLines] of HOTSPOT_LINE_LIMITS) {
    const actualLines = countLines(
      readFileSync(resolve(root, relativePath), "utf8"),
    );
    if (actualLines > maximumLines) {
      errors.push(
        `Architecture hotspot grew: ${relativePath} is ${actualLines} lines; baseline maximum is ${maximumLines}. Extract ownership instead of raising the limit.`,
      );
    }
  }

  return {
    contractVersion,
    errors,
    hotspotCount: HOTSPOT_LINE_LIMITS.size,
    migrationCount: migrationNames?.length ?? 0,
    workspaceManifestCount: discoveredManifests.length,
  };
}

export function writeSwiftContractMirror(root = process.cwd()) {
  const contractSource = readFileSync(resolve(root, CONTRACT_SOURCE), "utf8");
  const contractVersion = extractTypeScriptContractVersion(contractSource);
  if (!contractVersion) {
    throw new Error(
      `Expected one canonical CONTRACT_VERSION declaration at the start of ${CONTRACT_SOURCE}.`,
    );
  }
  const mirrorPath = resolve(root, IOS_CONTRACT_MIRROR);
  const swiftSource = readFileSync(mirrorPath, "utf8");
  const block = findSingleSwiftContractBlock(swiftSource);
  if (!block) {
    throw new Error(
      `Expected exactly one active iOS contract mirror in ${IOS_CONTRACT_MIRROR}.`,
    );
  }
  const lineEnding = block.text.includes("\r\n") ? "\r\n" : "\n";
  const replacement = renderSwiftContractMirror(contractVersion).replace(
    /\n/gu,
    lineEnding,
  );
  const nextSource =
    swiftSource.slice(0, block.index) +
    replacement +
    swiftSource.slice(block.index + block.text.length);
  writeFileSync(mirrorPath, nextSource);
  return {
    contractVersion,
    digest: createHash("sha256").update(nextSource).digest("hex"),
  };
}

const isMain =
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  if (process.argv.includes("--write-contract")) {
    const written = writeSwiftContractMirror(root);
    console.log(
      `Generated iOS contract mirror for ${written.contractVersion} (${written.digest.slice(0, 12)}).`,
    );
  }
  const result = checkArchitectureBoundaries(root);
  if (result.errors.length) {
    for (const error of result.errors) console.error(`ERROR ${error}`);
    console.error(
      `Architecture boundary check failed with ${result.errors.length} error(s).`,
    );
    process.exitCode = 1;
  } else {
    console.log(
      `Architecture boundaries passed: contract ${result.contractVersion}; ${result.migrationCount} migrations; ${result.workspaceManifestCount} workspace manifests; ${result.hotspotCount} hotspot baselines.`,
    );
  }
}
